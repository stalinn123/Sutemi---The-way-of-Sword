using UnityEngine;

namespace Kendo.Game
{
    /// <summary>
    /// Asset references for the running game. Created and filled by Kendo ▸ Build Game (KendoGameBuilder) and stored at
    /// Assets/_Project/Resources/KendoGameConfig.asset so every scene (and a direct Play in any scene) can load it.
    /// All referenced art is the supplied FBX content (or prefabs built from it); nothing here is a placeholder.
    /// </summary>
    [CreateAssetMenu(menuName = "Kendo/Game Config", fileName = "KendoGameConfig")]
    public sealed class KendoGameConfig : ScriptableObject
    {
        public const string ResourcePath = "KendoGameConfig";

        [Header("Characters (supplied FBX)")]
        [Tooltip("KendoMaster_And_Shinai.fbx model prefab – used for the master, the opponents and the former student.")]
        public GameObject characterModel;
        [Tooltip("Shinai prefab built from the sword nodes of the same FBX (root = grip end, +Y = blade).")]
        public GameObject shinaiPrefab;
        [Tooltip("Bogu_Men_Helmet.fbx model prefab.")]
        public GameObject menHelmet;
        public float menFitDrop = 0.06f;
        public float menScale = 1.0f;

        [Header("Environments (supplied FBX)")]
        public GameObject trainingDojo;
        public GameObject temple;
        public GameObject finalEnvironment;

        [Header("Badges (Badge_01..04 supplied, Badge_05 built from Badge_04)")]
        public GameObject[] badges = new GameObject[5];

        [Header("Material templates (keep URP Lit/Unlit in builds)")]
        public Material litTemplate;
        public Material unlitTemplate;

        [Header("UI")]
        public Sprite masterPortrait;
        public Sprite formerStudentPortrait;
        public Font font;

        [Header("AI")]
        [Tooltip("A2C base policy exported by Tools/AI/train_a2c.py.")]
        public TextAsset opponentPolicy;

        [Header("Audio (generated by Tools/Audio/gen_audio.py)")]
        public AudioClip musicDojo;
        public AudioClip musicBattle;
        public AudioClip musicFinal;
        public AudioClip ambienceDojo;
        public AudioClip ambienceTemple;
        public AudioClip shinaiHit;
        public AudioClip shinaiClash;
        public AudioClip shinaiTouch;
        public AudioClip fumikomi;
        public AudioClip footSlide;
        public AudioClip kiaiPlayer;
        public AudioClip kiaiOpponent;
        public AudioClip kiaiBoss;
        public AudioClip bell;
        public AudioClip taiko;
        public AudioClip uiClick;
        public AudioClip uiConfirm;
        public AudioClip success;
        public AudioClip fail;
        public AudioClip flagRaise;

        private static KendoGameConfig cached;

        public static KendoGameConfig Load()
        {
            if (cached == null) cached = Resources.Load<KendoGameConfig>(ResourcePath);
            return cached;
        }

        /// <summary>Lists what is missing so the boot screen can explain it instead of failing silently.</summary>
        public string MissingSummary()
        {
            var sb = new System.Text.StringBuilder();
            if (characterModel == null) sb.Append("character model, ");
            if (shinaiPrefab == null) sb.Append("shinai prefab, ");
            if (trainingDojo == null) sb.Append("training dojo, ");
            if (temple == null) sb.Append("temple, ");
            if (finalEnvironment == null) sb.Append("final environment, ");
            if (menHelmet == null) sb.Append("men helmet, ");
            for (int i = 0; i < badges.Length; i++) if (badges[i] == null) sb.Append($"badge {i + 1}, ");
            return sb.Length == 0 ? "" : sb.ToString(0, sb.Length - 2);
        }
    }
}
