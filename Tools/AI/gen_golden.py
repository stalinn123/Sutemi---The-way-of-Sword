"""Writes Assets/_Project/Tests/EditMode/Golden.g.cs: cases computed by the Python mirrors that the C# EditMode tests
replay (rules engine, duel simulator with scripted actions, MLP forward pass and one A2C update)."""
import sys, os, random, json
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Rules')); sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import rules_ref as R, duel_sim as D
from krandom import KRandom
from a2c import ActorCritic, A2C
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'Assets', '_Project', 'Tests', 'EditMode', 'Golden.g.cs')

def f(x): return f"{float(x):.6f}f"
def b(x): return 'true' if x else 'false'
lines = ['// <auto-generated> by Tools/AI/gen_golden.py – do not edit</auto-generated>', 'namespace Kendo.Tests', '{',
         '    public static class Golden', '    {']
# ---- strikes
rng = random.Random(11)
lines.append('        // target, contact, along, edge, hasuji, tip, arc, approach, kiai, kiaiOff, fumi, fumiOff, both, tilt, balanced, dist, opp, blocked, zObs, follow, restore, away, celebrated, profile(0 beg,1 int,2 shiai), allowTsuki, oppKamae | invalidReason, yuko, score')
lines.append('        public static readonly object[][] Strikes =')
lines.append('        {')
profs = [R.beginner(), R.intermediate(), R.shiai()]
for i in range(300):
    e = R.Evidence(target=rng.randrange(0, 9), contact=rng.random() < 0.9, contactAlongBlade=round(rng.random(), 3), edgeSide=rng.random() < 0.85,
        hasujiErrorDeg=round(rng.uniform(0, 70), 2), tipSpeed=round(rng.uniform(0, 14), 2), strikeArc=rng.random() < 0.8, approachSpeed=round(rng.uniform(0, 1.5), 2),
        kiai=rng.random() < 0.75, kiaiOffset=round(rng.uniform(-0.6, 0.6), 3), fumikomi=rng.random() < 0.7, fumikomiOffset=round(rng.uniform(-0.6, 0.6), 3),
        bothHands=rng.random() < 0.93, torsoTiltDeg=round(rng.uniform(0, 35), 1), balanced=rng.random() < 0.93, distance=round(rng.uniform(1.0, 3.2), 2),
        opportunity=rng.randrange(0, 7), blocked=rng.random() < 0.1, zanshinObserved=rng.random() < 0.85, followThrough=round(rng.uniform(0, 1), 2),
        kamaeRestoredAfter=round(rng.uniform(0.2, 3.5), 2), turnedAway=rng.random() < 0.1, celebrated=rng.random() < 0.04)
    pi = rng.randrange(0, 3); allow = rng.random() < 0.7; ok = rng.randrange(0, 2)
    ev = R.evaluate_strike(e, R.RuleConfig(allowTsuki=allow), profs[pi], ok)
    vals = [e.target, b(e.contact), f(e.contactAlongBlade), b(e.edgeSide), f(e.hasujiErrorDeg), f(e.tipSpeed), b(e.strikeArc), f(e.approachSpeed), b(e.kiai),
            f(e.kiaiOffset), b(e.fumikomi), f(e.fumikomiOffset), b(e.bothHands), f(e.torsoTiltDeg), b(e.balanced), f(e.distance), e.opportunity, b(e.blocked),
            b(e.zanshinObserved), f(e.followThrough), f(e.kamaeRestoredAfter), b(e.turnedAway), b(e.celebrated), pi, b(allow), ok, ev.invalidReason, b(ev.yukoDatotsu), f(ev.performanceScore)]
    lines.append('            new object[] { ' + ', '.join(str(v) for v in vals) + ' },')
lines.append('        };')
# ---- duel sim: scripted actions
lines.append('        // seed, steps, actions0 (repeating), actions1 (repeating) | points0, points1, hansoku0, hansoku1, phase, x0, x1')
lines.append('        public static readonly object[][] Duels =')
lines.append('        {')
for seed, a0, a1, steps in [(1, [1, 1, 5, 0, 0, 0], [0, 9, 0, 2, 0, 0], 300), (2, [1, 6, 0, 0, 2, 0], [1, 0, 5, 0, 0, 0], 300),
                            (3, [5, 0, 0, 0], [7, 0, 0, 0], 200), (4, [1, 1, 1, 1, 1, 1, 1, 1], [0], 60), (5, [3, 1, 8, 0, 4, 2], [10, 1, 6, 0], 400)]:
    sim = D.DuelSim(seed)
    for k in range(steps):
        if sim.done: break
        sim.step(a0[k % len(a0)], a1[k % len(a1)])
    vals = [seed, steps, '"' + ','.join(map(str, a0)) + '"', '"' + ','.join(map(str, a1)) + '"', sim.match.points[0], sim.match.points[1],
            sim.match.hansoku[0], sim.match.hansoku[1], sim.match.phase, f(sim.f[0].x), f(sim.f[1].x)]
    lines.append('            new object[] { ' + ', '.join(str(v) for v in vals) + ' },')
lines.append('        };')
# ---- MLP + A2C update
ac = ActorCritic(D.OBS_SIZE, D.N_ACTIONS, seed=5, hidden=16)
x = np.linspace(-1, 1, D.OBS_SIZE)
p = ac.policy(x)[0]; v = ac.value(x)[0]
lines.append('        public const string SmallNet = @"' + ac.to_json().replace('"', '""') + '";')
lines.append('        public static readonly float[] SmallNetPolicy = { ' + ', '.join(f(q) for q in p) + ' };')
lines.append(f'        public const float SmallNetValue = {f(v)};')
obs = np.stack([np.linspace(-1, 1, D.OBS_SIZE) * (k + 1) / 4 for k in range(4)]); acts = np.array([0, 5, 9, 1]); rets = np.array([0.5, -0.2, 1.0, 0.0])
opt = A2C(ac); opt.update(obs, acts, rets)
lines.append('        public static readonly int[] UpdateActions = { 0, 5, 9, 1 };')
lines.append('        public static readonly float[] UpdateReturns = { 0.5f, -0.2f, 1.0f, 0.0f };')
lines.append('        public static readonly float[] AfterUpdatePolicy = { ' + ', '.join(f(q) for q in ac.policy(x)[0]) + ' };')
lines.append(f'        public const float AfterUpdateValue = {f(ac.value(x)[0])};')
lines += ['    }', '}']
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote', OUT, len(lines), 'lines')
